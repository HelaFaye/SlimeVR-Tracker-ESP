"""Emit a KiCad project (.kicad_pro + .kicad_sch) for one board.

Connections are made with global labels rather than drawn wires. That is a deliberate
choice: auto-routing a readable schematic is a hard layout problem, while labelling every
pin is mechanical and produces something a human can actually follow. Anything sharing a
label is the same net, which KiCad's ERC and netlist export both understand.
"""
import argparse
import sys
import uuid
from pathlib import Path

import boards
import parts

OUT = Path(__file__).resolve().parents[1] / "out"
GRID = 2.54
COL_W = 63.5   # 25 grid units between component columns
ROW_H = 38.1   # 15 grid units between rows


def uid():
    return str(uuid.uuid4())


def label(net, x, y, rotation=0):
    return (
        f'  (global_label "{net}" (shape bidirectional) (at {x:.2f} {y:.2f} {rotation})\n'
        f"    (effects (font (size 1.27 1.27)) (justify left))\n"
        f"    (uuid {uid()})\n  )"
    )


def symbol_instance(comp, part, x, y):
    lib_id = part.symbol
    props = [
        f'    (property "Reference" "{comp.ref}" (at {x:.2f} {y - 12.7:.2f} 0)\n'
        "      (effects (font (size 1.27 1.27))))",
        f'    (property "Value" "{comp.value}" (at {x:.2f} {y + 12.7:.2f} 0)\n'
        "      (effects (font (size 1.27 1.27))))",
        f'    (property "Footprint" "{part.footprint}" (at {x:.2f} {y:.2f} 0)\n'
        "      (effects (font (size 1.27 1.27)) hide))",
    ]
    if part.lcsc:
        props.append(
            f'    (property "LCSC" "{part.lcsc}" (at {x:.2f} {y:.2f} 0)\n'
            "      (effects (font (size 1.27 1.27)) hide))"
        )
    if comp.note:
        props.append(
            f'    (property "Note" "{comp.note}" (at {x:.2f} {y:.2f} 0)\n'
            "      (effects (font (size 1.27 1.27)) hide))"
        )
    return (
        f'  (symbol (lib_id "{lib_id}") (at {x:.2f} {y:.2f} 0) (unit 1)\n'
        f"    (in_bom yes) (on_board yes) (uuid {uid()})\n"
        + "\n".join(props)
        + "\n  )"
    )


def build(board_key):
    board = boards.BOARDS[board_key]
    items = []
    per_row = 4

    for i, comp in enumerate(board["comps"]):
        part = parts.ALL_PARTS[comp.part]
        col, row = i % per_row, i // per_row
        x = 38.1 + col * COL_W
        y = 38.1 + row * ROW_H
        items.append(symbol_instance(comp, part, x, y))

        # Net labels stacked beside the symbol, one per pin.
        for j, (pin_num, net) in enumerate(sorted(comp.pins.items())):
            if net == "NC":
                continue
            items.append(
                label(net, x + 17.78, y - 10.16 + j * GRID)
            )

    title = board["title"]
    body = "\n".join(items)
    return f"""(kicad_sch (version 20230121) (generator slimevr_i2spi_gen)
  (uuid {uid()})
  (paper "A2")
  (title_block
    (title "{title}")
    (company "SlimeVR I2SPI")
    (comment 1 "Generated by hardware/gen/mksch.py - do not hand-edit, regenerate")
    (comment 2 "{board['description']}")
  )
  (lib_symbols)
{body}
  (sheet_instances (path "/" (page "1")))
)
"""


def project_file(name):
    return (
        '{\n  "board": {"design_settings": {}},\n'
        '  "meta": {"filename": "%s.kicad_pro", "version": 1},\n'
        '  "libraries": {"pinned_footprint_libs": [], "pinned_symbol_libs": []},\n'
        '  "schematic": {"legacy_lib_dir": "", "legacy_lib_list": []},\n'
        '  "sheets": [], "text_variables": {}\n}\n' % name
    )


def sym_lib_table():
    return (
        "(sym_lib_table\n"
        '  (lib (name "slimevr-i2spi")(type "KiCad")'
        '(uri "${KIPRJMOD}/../../lib/slimevr-i2spi.kicad_sym")(options "")(descr ""))\n)\n'
    )


def fp_lib_table():
    return (
        "(fp_lib_table\n"
        '  (lib (name "slimevr-i2spi")(type "KiCad")'
        '(uri "${KIPRJMOD}/../../lib/slimevr-i2spi.pretty")(options "")(descr ""))\n)\n'
    )


def generate(board_key, outdir=None):
    outdir = Path(outdir or OUT / board_key)
    outdir.mkdir(parents=True, exist_ok=True)
    name = f"slimevr-i2spi-{board_key}"
    (outdir / f"{name}.kicad_sch").write_text(build(board_key))
    (outdir / f"{name}.kicad_pro").write_text(project_file(name))
    (outdir / "sym-lib-table").write_text(sym_lib_table())
    (outdir / "fp-lib-table").write_text(fp_lib_table())
    return outdir / f"{name}.kicad_sch"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("board", choices=sorted(boards.BOARDS), nargs="?")
    ap.add_argument("--all", action="store_true")
    args = ap.parse_args()

    targets = sorted(boards.BOARDS) if args.all else [args.board]
    if not targets or targets == [None]:
        ap.error("name a board or pass --all")

    for key in targets:
        path = generate(key)
        n = len(boards.BOARDS[key]["comps"])
        print(f"  {key:<6} {n:>3} components -> {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
